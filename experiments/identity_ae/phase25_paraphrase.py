"""Phase 25: Paraphrase robustness test for the prompt-keyed library.

Phase 23/24 stored prompt engrams as keys but tested with the SAME prompt
used at absorption — trivially 100% routing. The real question: if a user
asks the same thing in different words, does the engram still match?

For each absorbed test, generate 2-3 paraphrased versions of the prompt
(same meaning, different surface form) and route them against the library.
Measure routing accuracy and retrieval rate per paraphrase.

Library stays prompt-keyed with 150 steps per adapter (phase 24 winner).

Usage:
    PYTHONPATH=/mnt/data/Code/HRS .venv/bin/python experiments/identity_ae/phase25_paraphrase.py
"""

import json
import re
import time
from pathlib import Path

import torch
from transformers import AutoTokenizer

from experiments.identity_ae.phase10_passkey import (
    check_passkey, load_model, generate_greedy,
)
from experiments.identity_ae.phase14_lora_l45 import L45_TARGETS
from experiments.identity_ae.phase16_combined import (
    val_ppl_ungated, RANK, HIGH_LR, BASE_LR,
)
from experiments.identity_ae.phase21_per_passage_adapters import train_passage_adapter
from experiments.identity_ae.phase22_engram_key import (
    make_key, cosine_match, reset_lora_to_zero, stratified_tests,
)
from experiments.identity_ae.lora_wrapper import (
    apply_lora, get_lora_state_dict, load_lora_state_dict,
)


N_STEPS = 150
SOURCE = "L5_mean"


def paraphrase(test):
    """Return 3 paraphrased versions of test['prompt']. Different surface
    forms, same meaning. Original is the question generated by phase 10."""
    p = test["prompt"]
    t = test["type"]

    if t == "numeric":
        # Original: "What is the system access code for the {fac} facility?"
        m = re.search(r"the (\w+) facility", p)
        fac = m.group(1)
        return [
            f"Tell me the access code for the {fac} facility.",
            f"Which code grants entry to the {fac} facility?",
            f"{fac.capitalize()} facility — what is the access code?",
        ]

    if t == "entity":
        # Original: "When did {name} make their breakthrough discovery?"
        m = re.search(r"When did (.+?) make", p)
        name = m.group(1)
        return [
            f"On what date did {name} make their breakthrough?",
            f"What was the date of {name}'s discovery?",
            f"{name}'s breakthrough — when did it happen?",
        ]

    if t == "technical":
        # Original: "What is the critical threshold of the {thing} in {unit}?"
        m = re.search(r"the (\w+) in (\w+)", p)
        thing, unit = m.group(1), m.group(2)
        return [
            f"At how many {unit} does the {thing} reach its critical threshold?",
            f"What {unit} value is the {thing}'s critical threshold?",
            f"{thing.capitalize()} criticality — how many {unit}?",
        ]

    if t == "fact":
        # Original: "How many signatories does the {proto} Protocol require?"
        m = re.search(r"the (\w+) Protocol", p)
        proto = m.group(1)
        return [
            f"What is the number of signatories required by the {proto} Protocol?",
            f"How many people must sign the {proto} Protocol?",
            f"{proto} Protocol — how many signatories?",
        ]

    raise ValueError(t)


def main():
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    tokenizer = AutoTokenizer.from_pretrained("gpt2")
    results_dir = Path("results/identity_ae/phase25")
    results_dir.mkdir(parents=True, exist_ok=True)

    model, cfg = load_model(device)
    n_lora = apply_lora(model, rank=RANK, alpha=RANK * 2, target_modules=L45_TARGETS)
    print(f"LoRA params per adapter: {n_lora:,}")
    print(f"Steps per adapter: {N_STEPS}")
    print(f"Key source: {SOURCE}")

    tests = stratified_tests()
    print(f"Stratified: 5 numeric + 5 entity + 5 technical + 5 fact = {len(tests)}")

    # Show one paraphrase example for sanity
    print(f"\nSample paraphrases for '{tests[0]['prompt']}':")
    for i, p in enumerate(paraphrase(tests[0])):
        print(f"  {i+1}. {p}")

    from data import load_wikitext, build_dataloaders
    splits, _ = load_wikitext(cfg.training.dataset, cfg.model.max_seq_len)
    loaders = build_dataloaders(splits, batch_size=4)

    reset_lora_to_zero(model)
    baseline_ppl = val_ppl_ungated(model, loaders["validation"], device)
    print(f"\nBaseline val PPL: {baseline_ppl:.3f}\n")

    # Absorption (same as phase 24)
    print(f"{'='*60}")
    print(f"ABSORPTION PHASE ({N_STEPS} steps each)")
    print(f"{'='*60}")
    library = []
    t0 = time.time()
    for i, test in enumerate(tests):
        reset_lora_to_zero(model)
        train_passage_adapter(model, test["passage"], tokenizer, device,
                               n_steps=N_STEPS, high_lr=HIGH_LR, base_lr=BASE_LR)
        prompt_ids = tokenizer.encode(test["prompt"], add_special_tokens=False)
        prompt_t = torch.tensor(prompt_ids, dtype=torch.long)[:512].unsqueeze(0).to(device)
        sd = {k: v.detach().cpu().clone() for k, v in get_lora_state_dict(model).items()}
        library.append((prompt_t, sd, dict(test)))
        if (i + 1) % 5 == 0:
            print(f"  [{i+1:2d}/20] absorbed {test['type']:9s}  ({time.time()-t0:.0f}s)")

    # Library keys from original prompts under base model
    reset_lora_to_zero(model)
    library_keys = [make_key(model, prompt_t, SOURCE) for prompt_t, _, _ in library]

    # ============================================================
    # PARAPHRASE RETRIEVAL
    # ============================================================
    print(f"\n{'='*60}")
    print("PARAPHRASE RETRIEVAL")
    print(f"{'='*60}")

    # Track per-paraphrase-slot results
    per_slot = [{"routing": 0, "retrieval": 0, "by_type": {}} for _ in range(3)]
    for slot in per_slot:
        for ptype in ["numeric", "entity", "technical", "fact"]:
            slot["by_type"][ptype] = {"routed": 0, "retrieved": 0}

    detailed = []

    for i, test in enumerate(tests):
        paraphrases = paraphrase(test)
        for slot_idx, para in enumerate(paraphrases):
            reset_lora_to_zero(model)
            ids = tokenizer.encode(para, add_special_tokens=False)
            ids_t = torch.tensor(ids, dtype=torch.long)[:512].unsqueeze(0).to(device)
            q = make_key(model, ids_t, SOURCE)
            best_idx, score = cosine_match(q, library_keys)

            correct = (best_idx == i)
            if correct:
                per_slot[slot_idx]["routing"] += 1
                per_slot[slot_idx]["by_type"][test["type"]]["routed"] += 1

            _, sd, _ = library[best_idx]
            sd_gpu = {k: v.to(device) for k, v in sd.items()}
            load_lora_state_dict(model, sd_gpu)

            gen = generate_greedy(model, para, tokenizer, device, 50)
            found = check_passkey(gen, test["passkey"])
            if found:
                per_slot[slot_idx]["retrieval"] += 1
                per_slot[slot_idx]["by_type"][test["type"]]["retrieved"] += 1

            detailed.append({
                "test_id": test["id"], "type": test["type"], "slot": slot_idx,
                "paraphrase": para, "passkey": test["passkey"],
                "best_idx": best_idx, "correct_route": correct,
                "found": found, "gen": gen[:120],
            })

    # ============================================================
    # SUMMARY
    # ============================================================
    print(f"\n{'='*60}")
    print(f"PHASE 25 SUMMARY (paraphrase robustness)")
    print(f"{'='*60}")
    print(f"  20 originals × 3 paraphrases each = 60 query trials")
    print()
    print(f"  {'Slot':6s} {'Routing':>10} {'Retrieval':>10}")
    print(f"  {'-'*28}")
    for i, slot in enumerate(per_slot):
        r = slot["routing"] / 20
        s = slot["retrieval"] / 20
        print(f"  {i+1:>4d}   {r:>10.0%} {s:>10.0%}")

    total_routing = sum(s["routing"] for s in per_slot)
    total_retrieval = sum(s["retrieval"] for s in per_slot)
    print(f"  {'-'*28}")
    print(f"  Total  {total_routing:>4d}/60   {total_retrieval:>4d}/60")
    print(f"  Avg    {total_routing/60:>10.0%} {total_retrieval/60:>10.0%}")

    print(f"\n  Per-type retrieval (across 3 paraphrases):")
    for ptype in ["numeric", "entity", "technical", "fact"]:
        ret = sum(s["by_type"][ptype]["retrieved"] for s in per_slot)
        rou = sum(s["by_type"][ptype]["routed"] for s in per_slot)
        print(f"    {ptype:9s}: routed {rou:2d}/15  retrieved {ret:2d}/15")

    # Failing paraphrases
    misses = [d for d in detailed if not d["found"]]
    if misses:
        print(f"\n  {len(misses)}/60 retrieval misses:")
        for m in misses[:10]:
            print(f"    [{m['type']}] '{m['paraphrase']}'")
            print(f"       passkey={m['passkey']!r}  routed_to={m['best_idx']} (correct={m['correct_route']})")
            print(f"       gen={m['gen']!r}")

    summary = {
        "n_steps": N_STEPS, "source": SOURCE,
        "n_originals": 20, "n_paraphrases_per": 3, "n_trials": 60,
        "per_slot": per_slot,
        "total_routing_pct": total_routing / 60,
        "total_retrieval_pct": total_retrieval / 60,
        "detailed": detailed,
    }
    with open(results_dir / "paraphrase.json", "w") as f:
        json.dump(summary, f, indent=2)
    print(f"\nResults saved to {results_dir}")


if __name__ == "__main__":
    main()
